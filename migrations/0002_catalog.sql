-- Divinity to your door: shared shelf, stock, and anonymous orders.
-- Orders store titles and totals only. Names, addresses, and card numbers
-- are never written here.

create table if not exists books (
  id text primary key,
  slug text not null unique,
  title text not null,
  author text not null,
  tradition text not null,
  language text not null,
  format text not null,
  pages integer not null,
  price_cents integer not null check (price_cents between 100 and 50000),
  stock integer not null check (stock >= 0 and stock <= 500),
  low_stock_at integer not null default 5,
  blurb text not null,
  description text not null,
  cover text not null,
  featured boolean not null default false,
  edition_no text not null,
  weight_g integer not null
);

create table if not exists orders (
  id text primary key,
  items text not null,
  subtotal_cents integer not null,
  shipping_cents integer not null,
  total_cents integer not null,
  region text not null,
  status text not null default 'paid' check (status in ('paid', 'returned')),
  created_at timestamptz not null default now()
);

create table if not exists stock_moves (
  id serial primary key,
  book_id text not null references books (id),
  delta integer not null,
  reason text not null,
  created_at timestamptz not null default now()
);

create index if not exists books_tradition_idx on books (tradition);
create index if not exists orders_created_idx on orders (created_at desc);

